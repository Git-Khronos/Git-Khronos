//! Bounded, purpose/context-bound native file-tool review authority.
//! Values are returned to the owner for cleanup outside its registry mutex.
use super::AppError;
use std::{
    collections::HashMap,
    time::{Duration, Instant},
};
const CAPACITY: usize = 8;
const LIFETIME: Duration = Duration::from_secs(5 * 60);
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub(super) enum Purpose {
    Launch,
    Merge,
    Stage,
    Cleanup,
}
struct Slot<T> {
    token: String,
    created: Instant,
    ready: Option<T>,
}
pub(super) struct ReviewStore<T> {
    entries: HashMap<(String, Purpose), Slot<T>>,
}
impl<T> Default for ReviewStore<T> {
    fn default() -> Self {
        Self {
            entries: HashMap::new(),
        }
    }
}
fn unavailable() -> AppError {
    AppError { kind: "fileToolReviewUnavailable".into(), message: "That tool review expired, changed, or was already used.".into(), hint: Some("Inspect the tool session and prepare a fresh review; do not repeat an uncertain action.".into()) }
}
fn context(value: &str) -> bool {
    !value.is_empty()
        && value.len() <= 128
        && value
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b"_-".contains(&b))
}
fn token(value: &str) -> bool {
    value.len() == 32
        && value
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}
impl<T> ReviewStore<T> {
    pub(super) fn prune(&mut self) -> Vec<T> {
        let expired: Vec<_> = self
            .entries
            .iter()
            .filter(|(_, slot)| slot.created.elapsed() >= LIFETIME)
            .map(|(key, _)| key.clone())
            .collect();
        expired
            .into_iter()
            .filter_map(|key| self.entries.remove(&key).and_then(|slot| slot.ready))
            .collect()
    }
    /// Entropy is generated by the native owner before this call. Pending and
    /// ready reviews share one cap; replacing ready state returns the old value.
    pub(super) fn reserve(
        &mut self,
        context_id: &str,
        purpose: Purpose,
        identifier: &str,
    ) -> Result<Option<T>, AppError> {
        if !context(context_id) || !token(identifier) {
            return Err(unavailable());
        }
        let key = (context_id.to_owned(), purpose);
        if self
            .entries
            .get(&key)
            .is_some_and(|slot| slot.ready.is_none())
            || (!self.entries.contains_key(&key) && self.entries.len() >= CAPACITY)
            || self.entries.values().any(|slot| slot.token == identifier)
        {
            return Err(unavailable());
        }
        Ok(self
            .entries
            .insert(
                key,
                Slot {
                    token: identifier.into(),
                    created: Instant::now(),
                    ready: None,
                },
            )
            .and_then(|slot| slot.ready))
    }
    /// A refused publication returns its value, so late/cancelled preparation
    /// cannot leak ownership or delete live tool files inside the cache lock.
    pub(super) fn publish(
        &mut self,
        context_id: &str,
        purpose: Purpose,
        identifier: &str,
        value: T,
    ) -> Result<(), (AppError, T)> {
        let slot = self
            .entries
            .get_mut(&(context_id.to_owned(), purpose))
            .filter(|slot| {
                slot.token == identifier
                    && slot.created.elapsed() < LIFETIME
                    && slot.ready.is_none()
            });
        let Some(slot) = slot else {
            return Err((unavailable(), value));
        };
        slot.ready = Some(value);
        Ok(())
    }
    pub(super) fn take(
        &mut self,
        context_id: &str,
        purpose: Purpose,
        identifier: &str,
    ) -> Result<T, AppError> {
        if !context(context_id) || !token(identifier) {
            return Err(unavailable());
        }
        let key = (context_id.to_owned(), purpose);
        if !self.entries.get(&key).is_some_and(|slot| {
            slot.token == identifier && slot.created.elapsed() < LIFETIME && slot.ready.is_some()
        }) {
            return Err(unavailable());
        }
        self.entries
            .remove(&key)
            .and_then(|slot| slot.ready)
            .ok_or_else(unavailable)
    }
    pub(super) fn discard(
        &mut self,
        context_id: &str,
        purpose: Purpose,
        identifier: &str,
    ) -> Result<Option<T>, AppError> {
        if !context(context_id) || !token(identifier) {
            return Err(unavailable());
        }
        let key = (context_id.to_owned(), purpose);
        if self
            .entries
            .get(&key)
            .is_some_and(|slot| slot.token == identifier)
        {
            return Ok(self.entries.remove(&key).and_then(|slot| slot.ready));
        }
        Ok(None)
    }
}

