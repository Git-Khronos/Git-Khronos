import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync, rmSync, openSync, ftruncateSync, closeSync, mkdirSync, symlinkSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { gunzipSync } from 'node:zlib';
import { prepareFrontendNotices } from './prepare-frontend-notices.mjs';

const notice = 'Package: owned-fixture\r\nLicense: "MIT"\r\n\r\nCopyright owned fixture contributors\r\nOwned fixture license terms.\n';
function fixture(t) {
  const root = mkdtempSync(join(tmpdir(), 'git-khronos-frontend-notices-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const file = join(root, '3rdpartylicenses.txt');
  writeFileSync(file, notice);
  return { root, file };
}

test('frontend notice preparation preserves exact generated bytes in deterministic gzip', t => {
  const f = fixture(t);
  const first = prepareFrontendNotices(f.file);
  assert.equal(gunzipSync(first).toString('utf8'), notice);
  assert.deepEqual(first, prepareFrontendNotices(f.file));
});

test('frontend notice preparation rejects absent, invalid, oversized or unreviewed records without leaking contents', t => {
  const f = fixture(t);
  for (const text of [Buffer.alloc(0), Buffer.from([0xff]), Buffer.from([0]), ' ', 'Package: fixture\n',
    'License: "MIT"\n', notice.replace('"MIT"', '"fixture-secret-unknown-license"'),
    notice.replace('"MIT"', '{fixture-secret-invalid-json}')]) {
    writeFileSync(f.file, text);
    assert.throws(() => prepareFrontendNotices(f.file), error =>
      /Cannot prepare generated frontend notices/.test(error.message) && !error.message.includes('fixture-secret'));
  }
  const descriptor = openSync(f.file, 'w');
  try { ftruncateSync(descriptor, 2 * 1024 * 1024 + 1); } finally { closeSync(descriptor); }
  assert.throws(() => prepareFrontendNotices(f.file));
  rmSync(f.file);
  assert.throws(() => prepareFrontendNotices(f.file));
  mkdirSync(f.file);
  assert.throws(() => prepareFrontendNotices(f.file));
});

test('frontend notice preparation rejects symbolic-link inputs before reading them', { skip: process.platform === 'win32' }, t => {
  const f = fixture(t);
  const linked = join(f.root, 'linked-notices.txt');
  symlinkSync(f.file, linked);
  assert.throws(() => prepareFrontendNotices(linked));
});

function identities(text) {
  const bytes = Buffer.from(text);
  return {
    sha256: createHash('sha256').update(bytes).digest('hex'),
    gitBlob: createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex'),
  };
}

function supplementFixture(t) {
  const f = fixture(t);
  const packageRoot = join(f.root, 'node_modules/@tauri-apps/plugin-dialog');
  const retainedRoot = join(f.root, 'packaging/licenses');
  mkdirSync(packageRoot, { recursive: true });
  mkdirSync(retainedRoot, { recursive: true });
  const manifest = { name: '@tauri-apps/plugin-dialog', version: '2.8.1', license: 'MIT OR Apache-2.0', repository: 'https://github.com/tauri-apps/plugins-workspace' };
  const manifestText = `${JSON.stringify(manifest)}\n`;
  const published = 'SPDXVersion: SPDX-2.1\nDataLicense: CC0-1.0\nOwned fixture metadata only.\n';
  writeFileSync(join(packageRoot, 'package.json'), manifestText);
  writeFileSync(join(packageRoot, 'LICENSE.spdx'), published);
  const generated = `Package: ${manifest.name}\nLicense: "${manifest.license}"\n\n${published}`;
  writeFileSync(f.file, generated);
  const revision = 'a'.repeat(40);
  const policy = {
    ...manifest, revision,
    sourceArchive: 'https://registry.npmjs.org/@tauri-apps/plugin-dialog/-/plugin-dialog-2.8.1.tgz',
    integrity: `sha512-${Buffer.alloc(64, 1).toString('base64')}`,
    manifestSha256: identities(manifestText).sha256, manifestGitBlob: identities(manifestText).gitBlob,
    manifestUpstream: `${manifest.repository}/blob/${revision}/plugins/dialog/package.json`,
    publishedNoticeSha256: identities(published).sha256, publishedNoticeGitBlob: identities(published).gitBlob,
    notices: ['MIT', 'APACHE-2.0'].map(kind => {
      const text = `Owned ${kind} fixture terms, not third-party implementation.\n`;
      const file = `fixture-LICENSE_${kind}`;
      writeFileSync(join(retainedRoot, file), text);
      return { file, upstream: `${manifest.repository}/blob/${revision}/LICENSE_${kind}`, ...identities(text) };
    }),
  };
  const lock = `packages:\n\n  '${manifest.name}@${manifest.version}':\n    resolution: {integrity: ${policy.integrity}}\n`;
  writeFileSync(join(f.root, 'pnpm-lock.yaml'), lock);
  const refresh = () => writeFileSync(join(retainedRoot, 'reviewed-frontend-notices.json'), JSON.stringify(policy));
  refresh();
  return { ...f, generated, packageRoot, retainedRoot, policy, refresh, prepare: () => prepareFrontendNotices(f.file, { repositoryRoot: f.root }) };
}

test('reviewed frontend supplement retains generated prefix and both exact license texts deterministically', t => {
  const f = supplementFixture(t);
  const result = f.prepare();
  const text = gunzipSync(result).toString('utf8');
  assert.ok(text.startsWith(f.generated));
  for (const file of f.policy.notices) {
    assert.ok(text.includes(readFileSync(join(f.retainedRoot, file.file), 'utf8')));
    assert.ok(text.includes(file.sha256));
    assert.ok(text.includes(file.upstream));
  }
  assert.ok(text.includes(f.policy.sourceArchive));
  assert.ok(!text.includes(f.root));
  assert.deepEqual(result, f.prepare());
});

test('reviewed frontend supplements reject changed package, published terms and lock provenance', t => {
  const mutations = [
    f => writeFileSync(join(f.packageRoot, 'package.json'), '{}'),
    f => writeFileSync(join(f.packageRoot, 'LICENSE.spdx'), 'Edited published metadata\n'),
    f => writeFileSync(join(f.packageRoot, 'LICENSE_MIT'), 'Newly published terms\n'),
    f => writeFileSync(join(f.root, 'pnpm-lock.yaml'), 'packages: {}\n'),
    f => writeFileSync(f.file, 'Package: different-fixture\nLicense: "MIT"\nOwned terms\n'),
    f => writeFileSync(join(f.retainedRoot, f.policy.notices[0].file), 'Edited fixture terms\n'),
  ];
  for (const mutate of mutations) {
    const f = supplementFixture(t);
    mutate(f);
    assert.throws(f.prepare, /Cannot prepare generated frontend notices/);
  }
});

test('frontend supplement policies cannot silently change version, sources, hashes or omit dual terms', t => {
  const mutations = [
    p => { p.version = '9.0.0'; }, p => { p.name = '../private-fixture'; },
    p => { p.repository = 'https://example.test/unknown'; },
    p => { p.sourceArchive = 'https://example.test/archive'; },
    p => { p.integrity = `sha512-${Buffer.alloc(64, 2).toString('base64')}`; },
    p => { p.manifestSha256 = 'b'.repeat(64); }, p => { p.publishedNoticeGitBlob = 'b'.repeat(40); },
    p => { p.manifestUpstream = `${p.repository}/blob/main/plugins/dialog/package.json`; },
    p => { p.notices.pop(); }, p => { p.notices[1] = p.notices[0]; },
    p => { p.notices[0].file = '../private-fixture'; },
    p => { p.notices[0].upstream = 'https://example.test/LICENSE'; },
    p => { p.notices[0].gitBlob = 'b'.repeat(40); },
  ];
  for (const mutate of mutations) {
    const f = supplementFixture(t);
    mutate(f.policy); f.refresh();
    assert.throws(f.prepare, /Cannot prepare generated frontend notices/);
  }
});

test('retained dialog-plugin notices keep their reviewed upstream byte identities', () => {
  const base = new URL('../packaging/licenses/', import.meta.url);
  const policy = JSON.parse(readFileSync(new URL('reviewed-frontend-notices.json', base), 'utf8'));
  assert.equal(policy.name, '@tauri-apps/plugin-dialog');
  assert.equal(policy.notices.length, 2);
  for (const file of policy.notices) {
    const bytes = readFileSync(new URL(file.file, base));
    assert.deepEqual(identities(bytes), { sha256: file.sha256, gitBlob: file.gitBlob });
    assert.ok(file.upstream.startsWith(`${policy.repository}/blob/${policy.revision}/`));
  }
});
